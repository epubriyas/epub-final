import { chromium } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1080 } })
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
await page.goto('http://localhost:3000/work', { waitUntil: 'networkidle', timeout: 120000 })
const stage = page.getByRole('region', { name: 'Selected portfolio previews' })
await stage.waitFor()
await stage.scrollIntoViewIfNeeded()
const card = stage.locator('[data-carousel-card]').first()
const before = await card.getAttribute('style')
await page.waitForTimeout(500)
if (before === (await card.getAttribute('style'))) throw Error('Carousel did not move')
await page.getByRole('button', { name: 'Pause motion' }).click()
await page.waitForTimeout(100)
const stopped = await card.getAttribute('style')
await page.waitForTimeout(350)
if (stopped !== (await card.getAttribute('style'))) throw Error('Pause failed')
const box = await stage.boundingBox()
await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
await page.mouse.down()
await page.mouse.move(box.x + box.width / 2 + 120, box.y + box.height / 2, { steps: 10 })
await page.mouse.up()
if (stopped === (await card.getAttribute('style'))) throw Error('Drag failed')
await mkdir('artifacts/portfolio-hero', { recursive: true })
await page.screenshot({ path: 'artifacts/portfolio-hero/desktop.png', fullPage: false })
for (const width of [320, 390, 768, 1440]) {
  await page.setViewportSize({ width, height: 950 })
  await page.waitForTimeout(150)
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth))
    throw Error(`Overflow ${width}`)
}
await page.setViewportSize({ width: 390, height: 844 })
await stage.scrollIntoViewIfNeeded()
await page.screenshot({ path: 'artifacts/portfolio-hero/mobile.png' })
await page.emulateMedia({ reducedMotion: 'reduce' })
await page.getByRole('button', { name: 'Resume motion' }).click()
await page.waitForTimeout(100)
const reduced = await card.getAttribute('style')
await page.waitForTimeout(350)
if (reduced !== (await card.getAttribute('style'))) throw Error('Reduced motion failed')
if (errors.length) throw Error(errors.join('\n'))
console.log('PASS: drift, pause, drag, 320/390/768/1440 overflow, reduced motion, no page errors')
await browser.close()
